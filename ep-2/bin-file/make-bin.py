code = bytearray([
    0xa9, 0xaa,
    0x8d, 0x00, 0x60,
    0xa9, 0x00,
    0xad, 0x00, 0x60,
    0x8d, 0x00, 0x40,
    0xa9, 0x00,
    0xad, 0x00, 0x40,
    0x4c, 0x00, 0x80
])

padding = bytearray([0xea]*(0x8000-len(code)))
rom = code + padding

rom[0x7ffc] = 0x00
rom[0x7ffd] = 0x80

with open('./rom.bin', 'wb') as out_file:
    out_file.write(rom)

print("Success!")